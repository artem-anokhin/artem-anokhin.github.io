import { hasCrisisWording } from "./crisis";

describe("hasCrisisWording", () => {
  it.each([
    "Иногда думаю, что не хочу жить",
    "хочется покончить с собой",
    "Мысли о суициде",
    "лучше бы меня не было",
    "опять режу себя",
    "I want to kill myself",
    "Жить не хочется совсем",
    "не хочу... жить",
    "Больше не могу жить так",
    "думаю наложить на себя руки",
    "Не хочу больше просыпаться",
    "селф-харм опять",
    "вчера резал себя",
    "думала, что повешусь",
    "Не хочу быть здесь",
    "не хочу больше существовать",
    "всем будет лучше без меня",
    "хочется уснуть и не проснуться",
    "думаю свести счёты с жизнью",
    "не вижу смысла в жизни",
    "всем было бы лучше без меня",
    "не хочу дальше жить",
    "жизнь не имеет смысла",
    "думаю про передоз",
    "хочу наглотаться таблеток",
  ])("flags: %s", (t) => expect(hasCrisisWording(t)).toBe(true));

  it.each([
    "",
    "Устал, но день был нормальный",
    "Убил весь вечер на сериал",
    "Сдал экзамен, хочу спать",
    "Умираю от скуки на паре",
    "Хочу уснуть пораньше",
    "Выпила таблетку от головы",
    "Курсовая",
  ])("ignores: %s", (t) => expect(hasCrisisWording(t)).toBe(false));
});
